-- =============================================================================
-- schema.sql : H2 2.x schema of the player data (port of data/donneesStats.sql)
-- =============================================================================
-- Ports parts 1, 2 and 4 of data/donneesStats.sql (PostgreSQL) and the view
-- v_player_tournament_stats of part 5 (plus v_team_tournament_stats, which has no PostgreSQL
-- counterpart). Part 3 (rating computation) is not ported:
-- the ratings come from data/donneesStats.json.
--
-- The script is idempotent (IF NOT EXISTS / CREATE OR REPLACE VIEW) and can run at
-- every startup. It contains no transaction control and no psql command.
--
-- Connection URL options (verified by SchemaScriptTest):
--   jdbc:h2:mem:<name>;MODE=PostgreSQL;NON_KEYWORDS=MINUTE,VALUE;DB_CLOSE_DELAY=-1
--   (file database: jdbc:h2:file:<path>;MODE=PostgreSQL;NON_KEYWORDS=MINUTE,VALUE)
--   - NON_KEYWORDS=MINUTE,VALUE : "minute" is a reserved word in H2 and is a column
--     of substitution, goal and booking. VALUE is listed as a precaution only.
--   - MODE=PostgreSQL : PostgreSQL compatibility (FILTER, BOOL_OR, CHAR semantics...).
--   - "match" is not reserved in H2 2.x and needs no option.
--
-- Deviations from data/donneesStats.sql:
--   1. team.fifa_code CHAR(3) NOT NULL added.
--   2. player_match_stats.is_goalkeeper BOOLEAN NOT NULL DEFAULT FALSE added.
--   3. referee.country_code is nullable.
--   4. The partial unique index uq_player_stats_motm (one man of the match per match)
--      is not created: H2 has no partial index. The importer test checks it instead.
--   5. SERIAL becomes an identity column that accepts explicit ids (BY DEFAULT).
--      TIMESTAMPTZ becomes TIMESTAMP WITH TIME ZONE.
--   6. CHECK (col IN (...)) becomes CHECK (col = ANY (ARRAY[...])) for stage, card and
--      result: with H2 2.4.240 an IN list in a CHECK is rejected as invalid as soon as the
--      session that created the table is closed (every later INSERT fails).
--   7. The view has no CROSS JOIN LATERAL (not supported by H2) and has two extra
--      columns: goalkeeper_matches and captain_matches.
-- =============================================================================

-- Reference tables -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS competition (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS team (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL UNIQUE,
    fifa_code  CHAR(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS stadium (
    id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(150) NOT NULL,
    city  VARCHAR(100) NOT NULL,
    UNIQUE (name, city)
);

CREATE TABLE IF NOT EXISTS referee (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL UNIQUE,
    country_code  CHAR(3)
);

CREATE TABLE IF NOT EXISTS player (
    id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(150) NOT NULL,
    team_id  INT NOT NULL REFERENCES team(id),
    UNIQUE (name, team_id)
);

-- Match ----------------------------------------------------------------------
-- Scores per period: ht (half time), ft (90 minutes), et (after extra time, NULL
-- otherwise), pen (penalty shoot-out, NULL otherwise).

CREATE TABLE IF NOT EXISTS match (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id  INT NOT NULL REFERENCES competition(id),
    stage           VARCHAR(20) NOT NULL CHECK (stage = ANY (ARRAY
                      ['GROUP', 'ROUND_OF_32', 'ROUND_OF_16', 'QUARTER_FINAL',
                       'SEMI_FINAL', 'THIRD_PLACE', 'FINAL'])),
    group_name      CHAR(1),                  -- 'A'..'L', NULL outside the group stage
    kickoff_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    stadium_id      INT NOT NULL REFERENCES stadium(id),
    attendance      INT,
    referee_id      INT REFERENCES referee(id),
    team1_id        INT NOT NULL REFERENCES team(id),
    team2_id        INT NOT NULL REFERENCES team(id),
    ht_team1        SMALLINT,
    ht_team2        SMALLINT,
    ft_team1        SMALLINT,
    ft_team2        SMALLINT,
    et_team1        SMALLINT,                 -- extra time, NULL otherwise
    et_team2        SMALLINT,
    pen_team1       SMALLINT,                 -- penalty shoot-out, NULL otherwise
    pen_team2       SMALLINT,
    CHECK (team1_id <> team2_id)
);

-- Match sheet ----------------------------------------------------------------
-- minute + added_time: "90+5" is stored as minute 90, added_time 5.

CREATE TABLE IF NOT EXISTS match_lineup (
    match_id    INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    player_id   INT NOT NULL REFERENCES player(id),
    team_id     INT NOT NULL REFERENCES team(id),
    is_starter  BOOLEAN NOT NULL,
    is_captain  BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (match_id, player_id)
);

CREATE TABLE IF NOT EXISTS substitution (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id       INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    team_id        INT NOT NULL REFERENCES team(id),
    player_in_id   INT NOT NULL REFERENCES player(id),
    player_out_id  INT NOT NULL REFERENCES player(id),
    minute         SMALLINT NOT NULL,
    added_time     SMALLINT
);

CREATE TABLE IF NOT EXISTS goal (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id     INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    team_id      INT NOT NULL REFERENCES team(id),    -- team that benefits from the goal
    player_id    INT NOT NULL REFERENCES player(id),  -- scorer (opponent for an own goal)
    minute       SMALLINT NOT NULL,
    added_time   SMALLINT,
    is_penalty   BOOLEAN NOT NULL DEFAULT FALSE,
    is_own_goal  BOOLEAN NOT NULL DEFAULT FALSE
);

-- Second yellow card: one 'Y' row then one 'Y/R' row for the same player.
CREATE TABLE IF NOT EXISTS booking (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id    INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    team_id     INT NOT NULL REFERENCES team(id),
    player_id   INT NOT NULL REFERENCES player(id),
    card        VARCHAR(3) NOT NULL CHECK (card = ANY (ARRAY['Y', 'R', 'Y/R'])),
    minute      SMALLINT NOT NULL,
    added_time  SMALLINT
);

CREATE TABLE IF NOT EXISTS penalty_kick (
    match_id    INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    kick_order  SMALLINT NOT NULL,
    team_id     INT NOT NULL REFERENCES team(id),
    player_id   INT NOT NULL REFERENCES player(id),
    scored      BOOLEAN NOT NULL,
    PRIMARY KEY (match_id, kick_order)
);

CREATE INDEX IF NOT EXISTS idx_match_stage    ON match(stage, group_name);
CREATE INDEX IF NOT EXISTS idx_goal_player    ON goal(player_id);
CREATE INDEX IF NOT EXISTS idx_booking_player ON booking(player_id);
CREATE INDEX IF NOT EXISTS idx_lineup_player  ON match_lineup(player_id);


-- Rating tables --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS player_match_rating (
    match_id                INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    player_id               INT NOT NULL REFERENCES player(id),
    team_id                 INT NOT NULL REFERENCES team(id),
    rating                  NUMERIC(3, 1) NOT NULL CHECK (rating BETWEEN 0 AND 10),
    minutes_played          SMALLINT NOT NULL,
    goals                   SMALLINT NOT NULL,
    penalty_goals           SMALLINT NOT NULL,
    own_goals               SMALLINT NOT NULL,
    decisive_goals          SMALLINT NOT NULL,  -- winning goal or final equalizer
    goals_for_on_pitch      SMALLINT NOT NULL,  -- team goals while the player is on the pitch
    goals_against_on_pitch  SMALLINT NOT NULL,
    yellow_cards            SMALLINT NOT NULL,
    sent_off                BOOLEAN  NOT NULL,
    shootout_scored         SMALLINT NOT NULL,
    shootout_missed         SMALLINT NOT NULL,
    algorithm_version       VARCHAR(20) NOT NULL,
    computed_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (match_id, player_id)
);

CREATE TABLE IF NOT EXISTS team_match_rating (
    match_id           INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    team_id            INT NOT NULL REFERENCES team(id),
    rating             NUMERIC(3, 1) NOT NULL CHECK (rating BETWEEN 0 AND 10),
    result             CHAR(1) NOT NULL CHECK (result = ANY (ARRAY['W', 'D', 'L'])),  -- at the end of play
    points             SMALLINT NOT NULL,                                   -- 3 / 1 / 0
    goals_for          SMALLINT NOT NULL,
    goals_against      SMALLINT NOT NULL,
    won_shootout       BOOLEAN,                                             -- NULL without shoot-out
    fair_play_points   SMALLINT NOT NULL,                                   -- FIFA scale, <= 0
    algorithm_version  VARCHAR(20) NOT NULL,
    computed_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (match_id, team_id)
);

CREATE INDEX IF NOT EXISTS idx_player_rating_player ON player_match_rating(player_id);
CREATE INDEX IF NOT EXISTS idx_team_rating_team     ON team_match_rating(team_id);


-- Detailed statistics per match ----------------------------------------------
-- NULL = unknown data, 0 = measured zero. The view keeps this distinction: a total
-- stays NULL as long as no match of the player has the data.

CREATE TABLE IF NOT EXISTS player_match_stats (
    match_id              INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    player_id             INT NOT NULL REFERENCES player(id),
    team_id               INT NOT NULL REFERENCES team(id),
    fouls_committed       SMALLINT CHECK (fouls_committed >= 0),
    free_kicks_won        SMALLINT CHECK (free_kicks_won >= 0),
    free_kicks_conceded   SMALLINT CHECK (free_kicks_conceded >= 0),
    duels_won             SMALLINT CHECK (duels_won >= 0),
    duels_lost            SMALLINT CHECK (duels_lost >= 0),
    corners               SMALLINT CHECK (corners >= 0),            -- corners taken
    offsides              SMALLINT CHECK (offsides >= 0),
    distance_km           NUMERIC(5, 2) CHECK (distance_km >= 0),
    is_man_of_the_match   BOOLEAN NOT NULL DEFAULT FALSE,
    is_goalkeeper         BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (match_id, player_id)
);

-- Not created in H2 (no partial index): one man of the match per match.
-- CREATE UNIQUE INDEX uq_player_stats_motm ON player_match_stats(match_id) WHERE is_man_of_the_match;
CREATE INDEX IF NOT EXISTS idx_player_stats_player ON player_match_stats(player_id);

-- Team totals as published (optional).
CREATE TABLE IF NOT EXISTS team_match_stats (
    match_id              INT NOT NULL REFERENCES match(id) ON DELETE CASCADE,
    team_id               INT NOT NULL REFERENCES team(id),
    fouls_committed       SMALLINT CHECK (fouls_committed >= 0),
    free_kicks_won        SMALLINT CHECK (free_kicks_won >= 0),
    free_kicks_conceded   SMALLINT CHECK (free_kicks_conceded >= 0),
    duels_won             SMALLINT CHECK (duels_won >= 0),
    duels_lost            SMALLINT CHECK (duels_lost >= 0),
    corners               SMALLINT CHECK (corners >= 0),
    offsides              SMALLINT CHECK (offsides >= 0),
    distance_km           NUMERIC(6, 2) CHECK (distance_km >= 0),
    PRIMARY KEY (match_id, team_id)
);


-- Tournament view ------------------------------------------------------------
-- One row per player and per competition: filter on competition_id.
-- Only players who entered the pitch are listed (they have a rating row).
-- yellow_cards = 'Y' cards, red_cards = 'R' and 'Y/R' cards. The bookings are
-- pre-aggregated per (match, player) instead of the PostgreSQL CROSS JOIN LATERAL.
-- goalkeeper_matches and captain_matches are scalar sub-queries: they do not
-- multiply the rows of the main query.
-- detailed_stats_matches = number of matches covered by player_match_stats.

CREATE OR REPLACE VIEW v_player_tournament_stats AS
SELECT m.competition_id,
       r.player_id,
       pl.name                                            AS player,
       r.team_id,
       t.name                                             AS team,
       COUNT(*)                                           AS matches_played,
       COUNT(*) FILTER (WHERE l.is_starter)               AS matches_started,
       SUM(r.minutes_played)                              AS minutes_played,
       SUM(r.goals)                                       AS goals,
       SUM(r.penalty_goals)                               AS penalty_goals,
       SUM(r.own_goals)                                   AS own_goals,
       SUM(COALESCE(bk.yellow, 0))                        AS yellow_cards,
       SUM(COALESCE(bk.red, 0))                           AS red_cards,
       SUM(s.fouls_committed)                             AS fouls_committed,
       SUM(s.free_kicks_won)                              AS free_kicks_won,
       SUM(s.free_kicks_conceded)                         AS free_kicks_conceded,
       SUM(s.duels_won)                                   AS duels_won,
       SUM(s.duels_lost)                                  AS duels_lost,
       SUM(s.corners)                                     AS corners,
       SUM(s.offsides)                                    AS offsides,
       SUM(s.distance_km)                                 AS distance_km,
       CASE WHEN COUNT(s.match_id) > 0
            THEN COUNT(*) FILTER (WHERE s.is_man_of_the_match) END AS man_of_the_match_count,
       CASE WHEN COUNT(s.match_id) > 0
            THEN BOOL_OR(s.is_man_of_the_match) END       AS man_of_the_match,
       COUNT(s.match_id)                                  AS detailed_stats_matches,
       ROUND(AVG(r.rating), 1)                            AS rating,
       ROUND(SUM(r.rating * r.minutes_played) / NULLIF(SUM(r.minutes_played), 0), 1) AS rating_weighted,
       (SELECT COUNT(*) FROM player_match_stats g
         WHERE g.player_id = r.player_id AND g.is_goalkeeper) AS goalkeeper_matches,
       (SELECT COUNT(*) FROM match_lineup c
         WHERE c.player_id = r.player_id AND c.is_captain)    AS captain_matches
FROM player_match_rating r
JOIN match m        ON m.id = r.match_id
JOIN player pl      ON pl.id = r.player_id
JOIN team t         ON t.id = r.team_id
JOIN match_lineup l ON l.match_id = r.match_id AND l.player_id = r.player_id
LEFT JOIN player_match_stats s ON s.match_id = r.match_id AND s.player_id = r.player_id
LEFT JOIN (
    SELECT b.match_id, b.player_id,
           COUNT(*) FILTER (WHERE b.card = 'Y')           AS yellow,
           COUNT(*) FILTER (WHERE b.card IN ('R', 'Y/R')) AS red
    FROM booking b
    GROUP BY b.match_id, b.player_id
) bk ON bk.match_id = r.match_id AND bk.player_id = r.player_id
GROUP BY m.competition_id, r.player_id, pl.name, r.team_id, t.name;


-- Team tournament view -------------------------------------------------------
-- One row per team and per competition: filter on competition_id.
-- Same card rules as v_player_tournament_stats; the cards are counted per team in the
-- booking table. Totals of team_match_stats stay NULL when no match has the data.
-- detailed_stats_matches = number of matches covered by team_match_stats.

CREATE OR REPLACE VIEW v_team_tournament_stats AS
SELECT m.competition_id,
       r.team_id,
       t.name                                             AS team,
       COUNT(*)                                           AS matches_played,
       COUNT(*) FILTER (WHERE r.result = 'W')             AS wins,
       COUNT(*) FILTER (WHERE r.result = 'D')             AS draws,
       COUNT(*) FILTER (WHERE r.result = 'L')             AS losses,
       SUM(r.points)                                      AS points,
       SUM(r.goals_for)                                   AS goals_for,
       SUM(r.goals_against)                               AS goals_against,
       SUM(COALESCE(bk.yellow, 0))                        AS yellow_cards,
       SUM(COALESCE(bk.red, 0))                           AS red_cards,
       SUM(r.fair_play_points)                            AS fair_play_points,
       SUM(s.fouls_committed)                             AS fouls_committed,
       SUM(s.free_kicks_won)                              AS free_kicks_won,
       SUM(s.free_kicks_conceded)                         AS free_kicks_conceded,
       SUM(s.duels_won)                                   AS duels_won,
       SUM(s.duels_lost)                                  AS duels_lost,
       SUM(s.corners)                                     AS corners,
       SUM(s.offsides)                                    AS offsides,
       SUM(s.distance_km)                                 AS distance_km,
       COUNT(s.match_id)                                  AS detailed_stats_matches,
       ROUND(AVG(r.rating), 1)                            AS rating
FROM team_match_rating r
JOIN match m ON m.id = r.match_id
JOIN team t  ON t.id = r.team_id
LEFT JOIN team_match_stats s ON s.match_id = r.match_id AND s.team_id = r.team_id
LEFT JOIN (
    SELECT b.match_id, b.team_id,
           COUNT(*) FILTER (WHERE b.card = 'Y')           AS yellow,
           COUNT(*) FILTER (WHERE b.card IN ('R', 'Y/R')) AS red
    FROM booking b
    GROUP BY b.match_id, b.team_id
) bk ON bk.match_id = r.match_id AND bk.team_id = r.team_id
GROUP BY m.competition_id, r.team_id, t.name;
